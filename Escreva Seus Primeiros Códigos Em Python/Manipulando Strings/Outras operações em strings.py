a = "Aurora Boreal"

print("Aurora" in a)
# Verificando se "Aurora" está em a
print("a" not in a)
# Verificando se "a" não está na variável a, o que é falso, pois "a" se encontra na variável a
# Tanto "In" quanto "not in" fazemos a verificação se uma string específica está contida em um objeto, sempre retornando um valor booleano
print("A " + a)
# Concatenando strings
print((a + "    ")  * 5)
# Misturando tipos de dados, para que a string contida em a, apareceça 5 vezes