# A sintaxe mais simples possível que a linguagem fornece, será: '{campo:align}'.format("String..."). Onde campo é o argumento que será usado, e align define o alinhamento dentro da largura padrão do Python/IDE.

print('{:>60}'.format("Olá"))
print('{:<60}'.format("Tudo bem?"))
print('{:^60}'.format("Eu me chamo Yzaak"))
